#!/usr/bin/env python3
"""Read-only release gate comparing two public Chromium homepage canaries.

Requires PNGs plus report.json generated by tests/browser_live_canary.js.
Never logs in, changes WordPress, clears caches or touches checkout/payment.
Use *after* a protected independent plugin migration. Reject any material
visual regression, even if HTTP and registered widgets still appear healthy.
"""
from argparse import ArgumentParser
import json
from pathlib import Path
import sys

try:
    from PIL import Image, ImageChops, ImageStat
except ImportError as exc:
    raise SystemExit("Pillow is required for pixel-fidelity verification") from exc


def evaluate(before: Path, after: Path):
    original = json.loads((before / "report.json").read_text(encoding="utf-8"))
    revised = json.loads((after / "report.json").read_text(encoding="utf-8"))
    checks = []
    report = {"passed": False, "read_only": True, "viewports": []}
    if (original.get("origin") != revised.get("origin")
            or original.get("origin") != "https://itzybitzyworkshop.co.uk"):
        raise ValueError("Both canaries must have exactly the trusted site origin")
    pre = {entry["label"]: entry for entry in original.get("viewports", [])}
    post = {entry["label"]: entry for entry in revised.get("viewports", [])}
    if set(pre) != {"desktop", "mobile"} or set(post) != {"desktop", "mobile"}:
        raise ValueError("Expected one desktop and one mobile record from each canary")
    for name in ("desktop", "mobile"):
        old, new = pre[name], post[name]
        i0 = Image.open(before / (name + "-home.png")).convert("RGB")
        i1 = Image.open(after / (name + "-home.png")).convert("RGB")
        if i0.size != i1.size:
            raise ValueError("Screenshot sizes differ at " + name)
        diff = ImageChops.difference(i0, i1)
        page_delta = sum(ImageStat.Stat(diff).mean) / 3
        head_delta = sum(ImageStat.Stat(diff.crop(
            (0, 0, i0.width, min(133, i0.height)))).mean) / 3
        baseline_errors = old.get("events", {})
        current_errors = new.get("events", {})
        old_dom = old.get("dom", {})
        new_dom = new.get("dom", {})
        matching = (
            old.get("status") == 200
            and new.get("status") == 200
            and new_dom.get("elementorWidgets", 0) == old_dom.get("elementorWidgets")
            and new_dom.get("widgetTypes") == old_dom.get("widgetTypes")
            and new_dom.get("brokenImages") <= old_dom.get("brokenImages", -1)
            and new_dom.get("horizontalOverflow") is False
            and current_errors.get("pageErrors", -1) <= baseline_errors.get("pageErrors", -1)
            and current_errors.get("firstPartyRequestFailures", 1) == 0
            and not current_errors.get("firstPartyHttpErrors")
            and head_delta <= 0.75
            and page_delta <= 1.0
        )
        report["viewports"].append({
            "name": name,
            "passed": matching,
            "http": new.get("status"),
            "widgets": new_dom.get("elementorWidgets"),
            "same_widget_types": new_dom.get("widgetTypes") == old_dom.get("widgetTypes"),
            "page_mean_rgb_diff": round(page_delta, 5),
            "header_mean_rgb_diff": round(head_delta, 5),
            "new_page_js_errors": current_errors.get("pageErrors"),
            "new_http_errors": len(current_errors.get("firstPartyHttpErrors", [])),
        })
        checks.append(matching)
    report["passed"] = all(checks)
    return report


def main():
    ap = ArgumentParser(description=__doc__)
    ap.add_argument("--before", required=True, type=Path)
    ap.add_argument("--after", required=True, type=Path)
    args = ap.parse_args()
    result = evaluate(args.before, args.after)
    print("ZMP_VISUAL_GATE_JSON=" + json.dumps(result, separators=(",", ":")))
    if not result["passed"]:
        print("VISUAL_GATE=FAIL; DO NOT PROMOTE LIVE MIGRATION", file=sys.stderr)
        return 2
    print("VISUAL_GATE=PASS")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as error:
        print("VISUAL_GATE_ERROR=" + str(error), file=sys.stderr)
        sys.exit(2)
